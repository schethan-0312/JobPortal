export function searchIndianCities(searchTerm: string): IndianCity[] {
  const term = searchTerm.trim().toLowerCase();
  if (!term) {
    return ALL_INDIAN_CITIES.slice(0, 15);
  }

  // Exact / Prefix matches first (cities starting with typed prefix), sorted alphabetically
  const prefixMatches = ALL_INDIAN_CITIES.filter((item) =>
    item.city.toLowerCase().startsWith(term) || item.displayName.toLowerCase().startsWith(term)
  ).sort((a, b) => a.city.localeCompare(b.city));

  // Contains matches (cities containing term elsewhere), sorted alphabetically
  const containsMatches = ALL_INDIAN_CITIES.filter(
    (item) =>
      !item.city.toLowerCase().startsWith(term) &&
      !item.displayName.toLowerCase().startsWith(term) &&
      (item.city.toLowerCase().includes(term) || item.displayName.toLowerCase().includes(term))
  ).sort((a, b) => a.city.localeCompare(b.city));

  return [...prefixMatches, ...containsMatches].slice(0, 25);
}
